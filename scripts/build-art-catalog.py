"""Project the reviewed asset register into a small browser module; no save data."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1];data=json.loads((root/'design/S11/资产登记.json').read_text())
rows=[]
for a in data['assets']:
 rows.append({'id':a['asset_id'],'name':a['name'],'actor':a.get('character_id'),'category':a['category'],'ageRange':a.get('age_range'),'outfit':a['outfit_context'],'native':a['path'],'dimensions':a['actual_dimensions'],'exports':[{k:e[k] for k in ['role','format','path','dimensions']} for e in a['exports']]})
(root/'src/art-catalog.js').write_text('// Generated by scripts/build-art-catalog.py from reviewed S11 assets.\nexport const ART_CATALOG='+json.dumps(rows,ensure_ascii=False,separators=(',',':'))+';\n')
